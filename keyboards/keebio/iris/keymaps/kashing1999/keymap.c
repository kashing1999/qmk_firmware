bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    if (record->event.pressed) {

        switch (keycode) {
            case GO_ASGN:
                SEND_STRING(":=");
                break;
            case GO_NOT:
                SEND_STRING("!=");
                break;
            case GO_NIL:
                SEND_STRING("nil");
                break;
            case GO_ERR:
                SEND_STRING("if err != nil {\n");
                break;
            case SH_HOME:
                SEND_STRING("cd ~/");
                break;
        }
    }
    return true;
};

bool encoder_update_user(uint8_t index, bool clockwise) {
    switch(biton32(layer_state)) {
        case _DVORAK:
            if ((get_mods() & MOD_BIT(KC_LGUI)) == MOD_BIT(KC_LGUI)) {
                clockwise ? tap_code16(C(G(KC_LEFT))) : tap_code16(C(G(KC_RGHT)));
            }
            else if ((get_mods() & MOD_BIT(KC_LALT)) == MOD_BIT(KC_LALT)) {
                clockwise ? tap_code16(S(A(KC_TAB))) : tap_code16(A(KC_TAB));
            }
            else if ((get_mods() & MOD_BIT(KC_LCTL)) == MOD_BIT(KC_LCTL)) {
                clockwise ? tap_code16(S(C(KC_TAB))) : tap_code16(C(KC_TAB));
            }
            else {
                clockwise ? tap_code(KC_VOLD) : tap_code(KC_VOLU);
            }
            break;
        case _NAV:
            clockwise ? tap_code(KC_MPRV) : tap_code(KC_MNXT);
            break;
    }
    return false;
}
